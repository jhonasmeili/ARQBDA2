CREATE TABLE PRODUTO(
    PRODUTO_ID INT NOT NULL,
    PRODUTO_NOME VARCHAR2(20),
    PRODUTO_PRECO NUMBER(6,2),
    PRIMARY KEY (PRODUTO_ID)
);

--1
CREATE SEQUENCE SEQ_PRODUTO_ID
    START WITH 100
    INCREMENT BY 1
    NOCACHE
    NOCYCLE;

INSERT INTO PRODUTO (PRODUTO_ID, PRODUTO_NOME, PRODUTO_PRECO) VALUES (SEQ_PRODUTO_ID.NEXTVAL, 'Calça', 77.99);

SELECT * FROM PRODUTO;

--2
--CURRVAL retorna o ultimo valor definido dentro da sequência
--NEXTVAL define um novo valor dentro da sequência, baseado em seus parâmetros, e o retorna

SELECT SEQ_PRODUTO_ID.CURRVAL FROM DUAL;

