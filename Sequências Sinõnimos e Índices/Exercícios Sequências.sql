--5
--O CACHE prealoca uma seuqência de numeros na memória para permitir acessos mais rápidos
--Com NOCACHE, cada requisição NEXTVAL precisa definir o próximo número no momento
--Assim, requisições constantes em uma seqência NOCACHE precisam constantemente gerar o próximo número
--Ao invés de simplesmente reupera-lo da memória e apenas gerear novos números quando o cache se esgota

CREATE SEQUENCE SEQ_TRANSACOES
    START WITH 0
    INCREMENT BY 1
    MINVALUE 0
    NOCACHE
    NOCYCLE;
    
ALTER SEQUENCE SEQ_TRANSACOES
    CACHE 10000;


    