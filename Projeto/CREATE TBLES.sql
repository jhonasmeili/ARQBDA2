DROP TABLE CARGO;
DROP TABLE MUNICIPIO;
DROP TABLE UF;
DROP TABLE REGIAO;



CREATE TABLE REGIAO(
    ID_REGIAO INT NOT NULL,
    NOME_REGIAO VARCHAR2(50) NOT NULL,
    PRIMARY KEY(ID_REGIAO)
);

CREATE TABLE UF(
    ID_UF INT NOT NULL,
    NOME_UF VARCHAR2(50) NOT NULL,
    SIGLA_UF VARCHAR2(2) NOT NULL UNIQUE,
    ID_REGIAO INT NOT NULL,
    PRIMARY KEY(ID_UF),
    FOREIGN KEY (ID_REGIAO) REFERENCES REGIAO (ID_REGIAO)
);

CREATE TABLE MUNICIPIO(
    ID_MUNICIPIO INT NOT NULL,
    ID_MUNICIPIO_TSE INT NOT NULL UNIQUE,
    NOME_MUNICIPIO VARCHAR2(50) NOT NULL,
    ID_UF INT NOT NULL,
    PRIMARY KEY(ID_MUNICIPIO),
    FOREIGN KEY (ID_UF) REFERENCES UF (ID_UF)
);

CREATE TABLE CARGO(
    ID_CARGO INT NOT NULL,
    NOME_CARGO VARCHAR2(25) NOT NULL,
    PRIMARY KEY (ID_CARGO)
);

CREATE TABLE PARTIDO(
    NUMERO_PARTIDO INT NOT NULL,
    SIGLA_PARTIDO VARCHAR2(20) NOT NULL UNIQUE,
    NOME_PARTIDO VARCHAR2(50) NOT NULL,
    PRES_PARTIDO VARCHAR(70) NOT NULL,
    PRIMARY KEY (NUMERO_PARTIDO)
);

CREATE TABLE CANDIDATO(
    CPF_CANDIDATO INT NOT NULL,
    NUMERO_CANDIDATO INT NOT NULL,
    ID_CARGO INT NOT NULL,
    ID_ABRANGENCIA INT NOT NULL,
    SIGLA_ABRANGENCIA VARCHAR2(2) NOT NULL,
    NUMERO_PARTIDO INT NOT NULL,
    NOME_CANDIDATO VARCHAR2(100) NOT NULL,
    PRIMARY KEY(CPF_CANDIDATO),
    FOREIGN KEY (ID_CARGO) REFERENCES CARGO (ID_CARGO),
    FOREIGN KEY (ID_ABRANGENCIA) REFERENCES UF (ID_UF),
    FOREIGN KEY (NUMERO_PARTIDO) REFERENCES PARTIDO (NUMERO_PARTIDO)
);

CREATE TABLE ZONA(
    ID_ZONA INT NOT NULL,
    ID_MUNICIPIO_TSE INT NOT NULL,
    PRIMARY KEY(ID_MUNICIPIO_TSE, ID_ZONA),
    FOREIGN KEY (ID_MUNICIPIO_TSE) REFERENCES MUNICIPIO (ID_MUNICIPIO_TSE)
);

